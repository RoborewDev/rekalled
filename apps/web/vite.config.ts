import { defineConfig, lazyPlugins } from "vite-plus";
import { devtools } from "@tanstack/devtools-vite";

import { tanstackStart } from "@tanstack/react-start/plugin/vite";

import viteReact from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { nitro } from "nitro/vite";

const config = defineConfig({
  // The env files live at the repo root, shared with the API. Vite's default envDir is this
  // app's directory, so without this the VITE_* values never reach the bundle. Only VITE_*
  // variables are exposed to the client; the root files' other values stay server-side.
  envDir: "../..",
  // routeTree.gen.ts is generated by the router plugin; formatting it would just churn.
  fmt: { ignorePatterns: ["src/routeTree.gen.ts"] },
  lint: {
    jsPlugins: [{ name: "vite-plus", specifier: "vite-plus/oxlint-plugin" }],
    rules: { "vite-plus/prefer-vite-plus-imports": "error" },
    options: { typeAware: true, typeCheck: true },
  },
  resolve: { tsconfigPaths: true },
  test: { include: ["src/**/*.test.{ts,tsx}"] },
  // Unit tests are plain TS: skip the app plugins (Start, Nitro) so Vitest exits cleanly.
  plugins: process.env.VITEST
    ? []
    : lazyPlugins(() => [
        devtools(),
        nitro({ rollupConfig: { external: [/^@sentry\//] } }),
        tailwindcss(),
        tanstackStart(),
        viteReact(),
      ]),
});

export default config;
